-- 13) Retur: sjekkliste, ev. vedlikehald med sperre og oppgåve ----------------
create or replace function public.utleige_retur(p_res uuid, p_sjekk jsonb, p_vedlikehald boolean, p_notat text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  r record; oppg uuid; meg text := (select id from public.ansatte where email = auth.email() and aktiv limit 1);
begin
  if meg is null then raise exception 'Ingen tilgang.'; end if;
  select res.*, p.namn as produkt, e.kode into r
    from public.utleige_reservasjon res
    join public.utleige_produkt p on p.id = res.produkt_id
    join public.utleige_eining e on e.id = res.eining_id
   where res.id = p_res and (res.butikk_id = public.min_butikk() or public.er_konsern_admin());
  if r is null then raise exception 'Fann ikkje reservasjonen.'; end if;
  if r.status not in ('utleigd', 'forseinka') then raise exception 'Berre utleigd utstyr kan returnerast.'; end if;

  if p_vedlikehald then
    insert into public.tasks (butikk_id, tittel, detalj, prioritet, ansatt, frist, kategori, gjentak, sjekkliste)
    values (r.butikk_id, format('Vedlikehald: %s (%s)', r.produkt, r.kode),
      format(E'Etter retur av U-%s.\n%s', r.nummer, coalesce(nullif(trim(p_notat), ''), 'Sjå sjekklista på reservasjonen.')),
      'høg', 'ufordelt', (now() at time zone 'Europe/Oslo')::date + 1, 'Lager', 'ingen', '[]'::jsonb)
    returning id into oppg;
    insert into public.utleige_sperre (butikk_id, eining_id, start, slutt, grunn, notat, oppgave_id)
    values (r.butikk_id, r.eining_id, now(), null, 'vedlikehald', coalesce(p_notat, ''), oppg);
    update public.utleige_eining set status = 'vedlikehald' where id = r.eining_id;
  end if;

  update public.utleige_reservasjon
     set status = case when p_vedlikehald then 'kontroll' else 'returnert' end,
         retur_sjekk = p_sjekk,
         oppgave_id = coalesce(oppg, oppgave_id),
         internt_notat = case when coalesce(trim(p_notat), '') = '' then internt_notat
                              else trim(both E'\n' from internt_notat || E'\n' || 'Retur: ' || trim(p_notat)) end
   where id = p_res;
  return jsonb_build_object('oppgave_id', oppg);
end $$;
revoke execute on function public.utleige_retur(uuid, jsonb, boolean, text) from public, anon;
grant execute on function public.utleige_retur(uuid, jsonb, boolean, text) to authenticated;

-- Sperre oppheva / ferdig vedlikehald: eininga tilgjengeleg igjen.
create or replace function public.utleige_frigjer(p_eining uuid)
returns void language plpgsql volatile security definer set search_path = public as $$
begin
  if not exists (select 1 from public.utleige_eining where id = p_eining
                 and (butikk_id = public.min_butikk() or public.er_konsern_admin())) then
    raise exception 'Fann ikkje eininga.';
  end if;
  update public.utleige_sperre set slutt = now() where eining_id = p_eining and (slutt is null or slutt > now()) and start <= now();
  delete from public.utleige_sperre where eining_id = p_eining and start > now() and grunn = 'vedlikehald' and slutt is null;
  update public.utleige_eining set status = 'tilgjengeleg' where id = p_eining;
end $$;
revoke execute on function public.utleige_frigjer(uuid) from public, anon;
grant execute on function public.utleige_frigjer(uuid) to authenticated;

-- 14) Dagleg/timevis: forseinka returar og påminningar -------------------------
create or replace function public.utleige_paaminningar()
returns integer language plpgsql volatile security definer set search_path = public as $$
declare r record; n int := 0;
begin
  for r in update public.utleige_reservasjon set status = 'forseinka'
            where status = 'utleigd' and slutt < now() returning id loop
    perform public.utleige_epost_lag(r.id, 'forseinka'); n := n + 1;
  end loop;
  for r in select id from public.utleige_reservasjon
            where status in ('stadfesta', 'klar') and start between now() and now() + interval '24 hours' loop
    perform public.utleige_epost_lag(r.id, 'paaminning_henting'); n := n + 1;
  end loop;
  for r in select id from public.utleige_reservasjon
            where status = 'utleigd' and slutt between now() and now() + interval '24 hours' loop
    perform public.utleige_epost_lag(r.id, 'paaminning_retur'); n := n + 1;
  end loop;
  return n;
end $$;
revoke execute on function public.utleige_paaminningar() from public, anon, authenticated;

do $$

-- =====================================================================
-- UTLEIGE  – utstyr, einingar, reservasjonar, sperrer, kundar, e-post
-- =====================================================================
-- Offentleg kundeside (/utleige) + administrasjon i appen.
--   * Produkt (det kunden ser) har fleire fysiske einingar med eigen ID.
--   * Ein reservasjon gjeld éi eining i ein periode. Databasen hindrar
--     overlappande reservasjonar av same eining (exclusion constraint),
--     så to samtidige bestillingar kan aldri få same maskin.
--   * Sperrer (vedlikehald, reparasjon, klargjering) blokkerer òg.
--   * Prisen blir rekna ut her (utleige_pris), aldri berre i nettlesaren.
--   * Kunden når berre dei offentlege funksjonane (utleige_katalog,
--     utleige_ledigheit, utleige_pris, utleige_send_forespurnad). Tabellane
--     er berre for innlogga tilsette i same butikk.
--   * E-post blir lagd i kø (utleige_epost) og send av edge-funksjonen
--     utleige-epost når ein e-postnøkkel er sett opp.
-- Krev multi-butikk.sql og ferie-modul.sql (kan_godkjenne). Idempotent.

create extension if not exists btree_gist with schema extensions;

-- 1) Innstillingar per butikk --------------------------------------------
create table if not exists public.utleige_innstillingar (
  butikk_id uuid primary key references public.butikkar(id) on delete cascade,
  offentleg boolean not null default false,          -- vis på kundesida
  vilkar text not null default '',
  hente_tid text not null default '09:00' check (hente_tid ~ '^\d{2}:\d{2}$'),
  retur_tid text not null default '12:00' check (retur_tid ~ '^\d{2}:\d{2}$'),
  maks_dagar int not null default 14 check (maks_dagar between 1 and 90),
  kontakt_telefon text not null default '',
  kontakt_epost text not null default '',
  updated_at timestamptz not null default now()
);

-- 2) Produkt ---------------------------------------------------------------
create table if not exists public.utleige_produkt (
  id uuid primary key default gen_random_uuid(),
  butikk_id uuid not null references public.butikkar(id) on delete cascade,
  namn text not null check (length(namn) between 1 and 120),
  beskriving text not null default '',
  kategori text not null default 'Verktøy',
  bilete_url text,
  dogn_pris numeric(10,2) not null check (dogn_pris >= 0),
  halvdag_pris numeric(10,2) check (halvdag_pris >= 0),  -- opptil 4 timar
  helg_pris numeric(10,2) check (helg_pris >= 0),        -- fredag–måndag
  gebyr numeric(10,2) not null default 0 check (gebyr >= 0),       -- klargjering
  depositum numeric(10,2) not null default 0 check (depositum >= 0),
  tilbehor text[] not null default '{}',
  aktiv boolean not null default true,
  sortering int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists utleige_produkt_butikk_idx on public.utleige_produkt (butikk_id);

-- 3) Fysiske einingar ------------------------------------------------------
-- status er det tilsette set for hand. «Reservert» og «Utleigd» blir rekna
-- ut frå reservasjonane.
create table if not exists public.utleige_eining (
  id uuid primary key default gen_random_uuid(),
  butikk_id uuid not null references public.butikkar(id) on delete cascade,
  produkt_id uuid not null references public.utleige_produkt(id) on delete cascade,
  kode text not null check (length(kode) between 1 and 40),
  status text not null default 'tilgjengeleg'
    check (status in ('tilgjengeleg', 'kontroll', 'vedlikehald', 'ikkje_tilgjengeleg')),
  notat text not null default '',
  created_at timestamptz not null default now(),
  unique (butikk_id, kode)
);
create index if not exists utleige_eining_produkt_idx on public.utleige_eining (produkt_id);

-- 4) Kundar ----------------------------------------------------------------
create table if not exists public.utleige_kunde (
  id uuid primary key default gen_random_uuid(),
  butikk_id uuid not null references public.butikkar(id) on delete cascade,
  namn text not null,
  telefon text not null,
  epost text not null default '',
  notat text not null default '',
  created_at timestamptz not null default now(),
  unique (butikk_id, telefon)
);

-- 5) Reservasjonar ---------------------------------------------------------
create table if not exists public.utleige_reservasjon (
  id uuid primary key default gen_random_uuid(),
  nummer int generated by default as identity (start with 1001) unique,
  butikk_id uuid not null references public.butikkar(id) on delete cascade,
  produkt_id uuid not null references public.utleige_produkt(id),
  eining_id uuid not null references public.utleige_eining(id),
  kunde_id uuid not null references public.utleige_kunde(id),
  start timestamptz not null,
  slutt timestamptz not null,
  status text not null default 'ny' check (status in
    ('ny', 'stadfesta', 'klar', 'utleigd', 'forseinka', 'returnert', 'kontroll', 'avbestilt', 'avslatt')),
  pris_leige numeric(10,2) not null default 0 check (pris_leige >= 0),
  gebyr numeric(10,2) not null default 0 check (gebyr >= 0),
  depositum numeric(10,2) not null default 0 check (depositum >= 0),
  pris_total numeric(10,2) not null default 0 check (pris_total >= 0),
  kunde_melding text not null default '',
  internt_notat text not null default '',
  retur_sjekk jsonb,
  oppgave_id uuid references public.tasks(id) on delete set null,
  vilkar_godtatt_at timestamptz,
  utlevert_at timestamptz, utlevert_av text references public.ansatte(id) on delete set null,
  returnert_at timestamptz, returnert_av text references public.ansatte(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (slutt > start)
);
create index if not exists utleige_res_butikk_idx on public.utleige_reservasjon (butikk_id, start);
create index if not exists utleige_res_kunde_idx on public.utleige_reservasjon (kunde_id);

-- Same eining kan aldri ha to aktive reservasjonar som overlappar.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'utleige_ingen_overlapp') then
    alter table public.utleige_reservasjon add constraint utleige_ingen_overlapp
      exclude using gist (eining_id with =, tstzrange(start, slutt, '[)') with &&)
      where (status in ('ny', 'stadfesta', 'klar', 'utleigd', 'forseinka'));
  end if;
end $$;

-- 6) Sperrer (vedlikehald, reparasjon, klargjering) ------------------------
create table if not exists public.utleige_sperre (
  id uuid primary key default gen_random_uuid(),
  butikk_id uuid not null references public.butikkar(id) on delete cascade,
  eining_id uuid not null references public.utleige_eining(id) on delete cascade,
  start timestamptz not null,
  slutt timestamptz,                                   -- null = til vidare
  grunn text not null default 'vedlikehald' check (grunn in ('vedlikehald', 'reparasjon', 'klargjering')),
  notat text not null default '',
  oppgave_id uuid references public.tasks(id) on delete set null,
  created_at timestamptz not null default now(),
  check (slutt is null or slutt > start)
);
create index if not exists utleige_sperre_eining_idx on public.utleige_sperre (eining_id);

-- 7) E-postkø ----------------------------------------------------------------
create table if not exists public.utleige_epost (
  id uuid primary key default gen_random_uuid(),
  butikk_id uuid not null references public.butikkar(id) on delete cascade,
  reservasjon_id uuid references public.utleige_reservasjon(id) on delete cascade,
  type text not null,
  til text not null,
  emne text not null,
  tekst text not null,
  status text not null default 'ventar' check (status in ('ventar', 'sendt', 'feil', 'hoppa_over')),
  feil text,
  created_at timestamptz not null default now(),
  sendt_at timestamptz
);
create index if not exists utleige_epost_ventar_idx on public.utleige_epost (status) where status = 'ventar';
create unique index if not exists utleige_epost_paaminning_idx on public.utleige_epost (reservasjon_id, type)
  where type in ('paaminning_henting', 'paaminning_retur', 'forseinka');

-- 8) butikk_id automatisk + tilgang -----------------------------------------
do $$
declare t text;
begin
  for t in select unnest(array['utleige_produkt', 'utleige_eining', 'utleige_kunde', 'utleige_reservasjon', 'utleige_sperre', 'utleige_epost']) loop
    execute format('drop trigger if exists set_butikk on public.%I', t);
    execute format('create trigger set_butikk before insert on public.%I for each row execute function public.set_butikk_id()', t);
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "butikk_les" on public.%I', t);
    execute format('drop policy if exists "butikk_skriv" on public.%I', t);
    execute format('create policy "butikk_les" on public.%I for select to authenticated using (butikk_id = public.min_butikk() or public.er_konsern_admin())', t);
  end loop;
end $$;
alter table public.utleige_innstillingar enable row level security;
-- Éi innstillingsrad per butikk (kundesida er av til ho blir slått på).
insert into public.utleige_innstillingar (butikk_id)
select b.id from public.butikkar b
on conflict (butikk_id) do nothing;

-- Produkt, einingar og innstillingar: berre leiar/godkjennar endrar.
do $$
declare t text;
begin
  for t in select unnest(array['utleige_produkt', 'utleige_eining']) loop
    execute format('create policy "butikk_skriv" on public.%I for all to authenticated
      using ((public.kan_godkjenne() and butikk_id = public.min_butikk()) or public.er_konsern_admin())
      with check ((public.kan_godkjenne() and butikk_id = public.min_butikk()) or public.er_konsern_admin())', t);
  end loop;
  -- Reservasjonar, kundar og sperrer: alle tilsette i butikken.
  for t in select unnest(array['utleige_kunde', 'utleige_reservasjon', 'utleige_sperre']) loop
    execute format('create policy "butikk_skriv" on public.%I for all to authenticated
      using (butikk_id = public.min_butikk() or public.er_konsern_admin())
      with check (butikk_id = public.min_butikk() or public.er_konsern_admin())', t);
  end loop;
end $$;
drop policy if exists "butikk_les" on public.utleige_innstillingar;
drop policy if exists "butikk_skriv" on public.utleige_innstillingar;
create policy "butikk_les" on public.utleige_innstillingar for select to authenticated
  using (butikk_id = public.min_butikk() or public.er_konsern_admin());
create policy "butikk_skriv" on public.utleige_innstillingar for all to authenticated
  using ((public.kan_godkjenne() and butikk_id = public.min_butikk()) or public.er_konsern_admin())
  with check ((public.kan_godkjenne() and butikk_id = public.min_butikk()) or public.er_konsern_admin());

-- 9) Prisutrekning -------------------------------------------------------------
-- Opptil 4 timar: halvdagspris (om sett). Fredag–måndag (maks 3 døgn, start
-- fredag): helgepris (om sett). Elles døgnpris × påbyrja døgn.
create or replace function public.utleige_pris(p_produkt uuid, p_start timestamptz, p_slutt timestamptz)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  p record;
  timar numeric := extract(epoch from (p_slutt - p_start)) / 3600;
  dagar int := greatest(1, ceil(timar / 24)::int);
  start_lokal timestamp := p_start at time zone 'Europe/Oslo';
  slutt_lokal timestamp := p_slutt at time zone 'Europe/Oslo';
  leige numeric; modell text;
begin
  select * into p from public.utleige_produkt where id = p_produkt;
  if p is null then raise exception 'Ukjent produkt.'; end if;
  if p_slutt <= p_start then raise exception 'Sluttid må vere etter starttid.'; end if;

  if p.halvdag_pris is not null and timar <= 4 then
    leige := p.halvdag_pris; modell := 'halvdag';
  elsif p.helg_pris is not null and extract(isodow from start_lokal) = 5
        and slutt_lokal::date <= start_lokal::date + 3 and dagar <= 3 then
    leige := p.helg_pris; modell := 'helg';
  else
    leige := p.dogn_pris * dagar; modell := 'dogn';
  end if;

  return jsonb_build_object(
    'modell', modell, 'dagar', dagar, 'timar', round(timar, 1),
    'leige', leige, 'gebyr', p.gebyr, 'depositum', p.depositum,
    'total', leige + p.gebyr
  );
end $$;

-- 10) Ledigheit ----------------------------------------------------------------
-- Kan eininga leigast ut i perioden? (status, sperrer, aktive reservasjonar)
create or replace function public.utleige_eining_ledig(p_eining uuid, p_start timestamptz, p_slutt timestamptz, p_utan uuid default null)
returns boolean language sql stable security definer set search_path = public as $$
  select
    exists (select 1 from public.utleige_eining e where e.id = p_eining and e.status = 'tilgjengeleg')
    and not exists (
      select 1 from public.utleige_sperre s where s.eining_id = p_eining
        and tstzrange(s.start, coalesce(s.slutt, 'infinity'), '[)') && tstzrange(p_start, p_slutt, '[)'))
    and not exists (
      select 1 from public.utleige_reservasjon r where r.eining_id = p_eining
        and r.id is distinct from p_utan
        and r.status in ('ny', 'stadfesta', 'klar', 'utleigd', 'forseinka')
        and tstzrange(r.start, r.slutt, '[)') && tstzrange(p_start, p_slutt, '[)'));
$$;

-- Sperrer og reservasjonar kan ikkje krysse kvarandre (eigne tabellar, så
-- sjekken skjer i ein trigger med lås per eining).
create or replace function public.utleige_res_vakt()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  meg text := (select id from public.ansatte where email = auth.email() limit 1);
begin
  perform pg_advisory_xact_lock(hashtext(new.eining_id::text));
  if new.status in ('ny', 'stadfesta', 'klar', 'utleigd', 'forseinka') and exists (
    select 1 from public.utleige_sperre s where s.eining_id = new.eining_id
      and tstzrange(s.start, coalesce(s.slutt, 'infinity'), '[)') && tstzrange(new.start, new.slutt, '[)'))
    -- Ein reservasjon som alt er utlevert, kan halde fram sjølv om nokon sperrar.
    and (tg_op = 'INSERT' or new.start is distinct from old.start or new.slutt is distinct from old.slutt
         or new.eining_id is distinct from old.eining_id or old.status not in ('ny', 'stadfesta', 'klar', 'utleigd', 'forseinka'))
  then
    raise exception 'Eininga er sperra (vedlikehald) i perioden.' using errcode = 'P0001';
  end if;
  if (select produkt_id from public.utleige_eining where id = new.eining_id) is distinct from new.produkt_id then
    raise exception 'Eininga høyrer ikkje til produktet.';
  end if;

  new.updated_at := now();
  if tg_op = 'UPDATE' and new.status is distinct from old.status then
    if new.status = 'utleigd' and old.status <> 'forseinka' then
      new.utlevert_at := coalesce(new.utlevert_at, now()); new.utlevert_av := coalesce(new.utlevert_av, meg);
    elsif new.status in ('returnert', 'kontroll') then
      new.returnert_at := coalesce(new.returnert_at, now()); new.returnert_av := coalesce(new.returnert_av, meg);
    end if;
  end if;
  return new;
end $$;
revoke execute on function public.utleige_res_vakt() from public, anon, authenticated;
drop trigger if exists utleige_res_vakt on public.utleige_reservasjon;
create trigger utleige_res_vakt before insert or update on public.utleige_reservasjon
  for each row execute function public.utleige_res_vakt();

create or replace function public.utleige_sperre_vakt()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(hashtext(new.eining_id::text));
  return new;
end $$;
revoke execute on function public.utleige_sperre_vakt() from public, anon, authenticated;
drop trigger if exists utleige_sperre_vakt on public.utleige_sperre;
create trigger utleige_sperre_vakt before insert or update on public.utleige_sperre
  for each row execute function public.utleige_sperre_vakt();

-- 11) E-post ved førespurnad, stadfesting, endring og avbestilling ------------
create or replace function public.utleige_tid(t timestamptz)
returns text language sql immutable set search_path = public as $$
  select to_char(t at time zone 'Europe/Oslo', 'DD.MM.YYYY "kl." HH24:MI');
$$;

-- «kr 1 199,00»
create or replace function public.utleige_kr(n numeric)
returns text language sql immutable set search_path = public as $$
  select 'kr ' || replace(replace(to_char(coalesce(n, 0), 'FM999,999,990.00'), ',', ' '), '.', ',');
$$;

create or replace function public.utleige_epost_lag(p_res uuid, p_type text)
returns void language plpgsql security definer set search_path = public as $$
declare
  r record; emne text; tekst text; innleiing text;
begin
  select res.*, k.namn as kunde_namn, k.epost, p.namn as produkt, e.kode, b.namn as butikk,
         coalesce(i.kontakt_telefon, '') as tlf
    into r
    from public.utleige_reservasjon res
    join public.utleige_kunde k on k.id = res.kunde_id
    join public.utleige_produkt p on p.id = res.produkt_id
    join public.utleige_eining e on e.id = res.eining_id
    join public.butikkar b on b.id = res.butikk_id
    left join public.utleige_innstillingar i on i.butikk_id = res.butikk_id
   where res.id = p_res;
  if r is null then return; end if;

  case p_type
    when 'motteken' then emne := 'Vi har motteke førespurnaden din'; innleiing := 'Takk! Vi har motteke førespurnaden din og stadfestar så snart vi har sett på han.';
    when 'stadfesta' then emne := 'Leiga di er stadfesta'; innleiing := 'Leiga di er stadfesta. Velkomen til å hente utstyret.';
    when 'endra' then emne := 'Leiga di er endra'; innleiing := 'Leiga di er endra. Her er dei oppdaterte detaljane.';
    when 'avbestilt' then emne := 'Leiga di er avbestilt'; innleiing := 'Leiga di er avbestilt.';
    when 'avslatt' then emne := 'Vi kan dessverre ikkje leige ut i denne perioden'; innleiing := 'Vi kan dessverre ikkje stadfeste førespurnaden din for denne perioden. Ta gjerne kontakt for andre datoar.';
    when 'paaminning_henting' then emne := 'Påminning: henting av utleigeutstyr'; innleiing := 'Påminning om at du skal hente utstyret.';
    when 'paaminning_retur' then emne := 'Påminning: retur av utleigeutstyr'; innleiing := 'Påminning om at utstyret skal leverast tilbake.';
    when 'forseinka' then emne := 'Utleigeutstyret skulle vore levert'; innleiing := 'Utstyret skulle vore levert tilbake. Gi oss beskjed om du treng å forlengje leiga.';
    else return;
  end case;

  tekst := format(E'Hei %s,\n\n%s\n\nReservasjon: U-%s\nUtstyr: %s\nHenting: %s\nRetur: %s\nLeigepris: %s (inkl. gebyr)\nDepositum: %s\n\nHelsing\n%s%s',
    r.kunde_namn, innleiing, r.nummer, r.produkt, public.utleige_tid(r.start), public.utleige_tid(r.slutt),
    public.utleige_kr(r.pris_total), public.utleige_kr(r.depositum),
    r.butikk, case when r.tlf <> '' then E'\nTlf. ' || r.tlf else '' end);

  insert into public.utleige_epost (butikk_id, reservasjon_id, type, til, emne, tekst, status)
  values (r.butikk_id, p_res, p_type, r.epost, emne, tekst, case when r.epost = '' then 'hoppa_over' else 'ventar' end)
  on conflict do nothing;
end $$;
revoke execute on function public.utleige_epost_lag(uuid, text) from public, anon, authenticated;

create or replace function public.utleige_res_epost()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    perform public.utleige_epost_lag(new.id, 'motteken');
  elsif new.status is distinct from old.status and new.status in ('stadfesta', 'avbestilt', 'avslatt') then
    perform public.utleige_epost_lag(new.id, new.status);
  elsif new.status in ('ny', 'stadfesta', 'klar')
    and (new.start is distinct from old.start or new.slutt is distinct from old.slutt or new.produkt_id is distinct from old.produkt_id) then
    perform public.utleige_epost_lag(new.id, 'endra');
  end if;
  return null;
end $$;
revoke execute on function public.utleige_res_epost() from public, anon, authenticated;
drop trigger if exists utleige_res_epost on public.utleige_reservasjon;
create trigger utleige_res_epost after insert or update on public.utleige_reservasjon
  for each row execute function public.utleige_res_epost();

-- 12) Offentlege funksjonar (kundesida, utan innlogging) ----------------------
create or replace function public.utleige_katalog()
returns table(id uuid, butikk_id uuid, butikk text, namn text, beskriving text, kategori text, bilete_url text,
              dogn_pris numeric, halvdag_pris numeric, helg_pris numeric, gebyr numeric, depositum numeric,
              tilbehor text[], einingar int, vilkar text, hente_tid text, retur_tid text, maks_dagar int)
language sql stable security definer set search_path = public as $$
  select p.id, p.butikk_id, b.namn, p.namn, p.beskriving, p.kategori, p.bilete_url,
         p.dogn_pris, p.halvdag_pris, p.helg_pris, p.gebyr, p.depositum, p.tilbehor,
         (select count(*)::int from public.utleige_eining e where e.produkt_id = p.id and e.status <> 'ikkje_tilgjengeleg'),
         i.vilkar, i.hente_tid, i.retur_tid, i.maks_dagar
  from public.utleige_produkt p
  join public.butikkar b on b.id = p.butikk_id and b.aktiv
  join public.utleige_innstillingar i on i.butikk_id = p.butikk_id and i.offentleg
  where p.aktiv
  order by b.namn, p.sortering, p.namn;
$$;

-- Ledige einingar per dag (for kalenderen på kundesida).
create or replace function public.utleige_ledigheit(p_produkt uuid, p_fra date, p_dagar int default 42)
returns table(dato date, ledige int, totalt int)
language sql stable security definer set search_path = public as $$
  with dagar as (
    select d::date as dato,
           (d::date::timestamp at time zone 'Europe/Oslo') as fra,
           ((d::date + 1)::timestamp at time zone 'Europe/Oslo') as til
    from generate_series(p_fra, p_fra + least(greatest(p_dagar, 1), 92) - 1, interval '1 day') d
  ), einingar as (
    select e.id from public.utleige_eining e
    join public.utleige_produkt p on p.id = e.produkt_id and p.aktiv
    join public.utleige_innstillingar i on i.butikk_id = p.butikk_id and i.offentleg
    where e.produkt_id = p_produkt and e.status = 'tilgjengeleg'
  )
  select d.dato,
         (select count(*)::int from einingar e where public.utleige_eining_ledig(e.id, d.fra, d.til)),
         (select count(*)::int from einingar)
  from dagar d order by d.dato;
$$;

-- Kan produktet leigast i perioden? Pris + tal ledige einingar.
create or replace function public.utleige_sjekk(p_produkt uuid, p_start timestamptz, p_slutt timestamptz)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare ledige int;
begin
  if not exists (
    select 1 from public.utleige_produkt p join public.utleige_innstillingar i on i.butikk_id = p.butikk_id and i.offentleg
    where p.id = p_produkt and p.aktiv) then
    raise exception 'Produktet finst ikkje.';
  end if;
  select count(*) into ledige from public.utleige_eining e
   where e.produkt_id = p_produkt and public.utleige_eining_ledig(e.id, p_start, p_slutt);
  return public.utleige_pris(p_produkt, p_start, p_slutt) || jsonb_build_object('ledige', ledige);
end $$;

-- Send førespurnad. Vel ei ledig eining under lås, så to samtidige
-- førespurnader ikkje kan få same maskin (exclusion constraint er siste vern).
create or replace function public.utleige_send_forespurnad(
  p_produkt uuid, p_start timestamptz, p_slutt timestamptz,
  p_namn text, p_telefon text, p_epost text, p_melding text, p_vilkar boolean)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  p record; i record; eining uuid; kunde uuid; pris jsonb; res record;
  tlf text := regexp_replace(coalesce(p_telefon, ''), '[^0-9+]', '', 'g');
  epost text := lower(trim(coalesce(p_epost, '')));
  namn text := trim(coalesce(p_namn, ''));
begin
  select * into p from public.utleige_produkt where id = p_produkt and aktiv;
  if p is null then raise exception 'Produktet finst ikkje.'; end if;
  select * into i from public.utleige_innstillingar where butikk_id = p.butikk_id and offentleg;
  if i is null then raise exception 'Utleige er ikkje opna for denne butikken.'; end if;

  if length(namn) < 2 or length(namn) > 100 then raise exception 'Skriv inn namnet ditt.'; end if;
  if length(regexp_replace(tlf, '\D', '', 'g')) not between 8 and 15 then raise exception 'Skriv inn eit gyldig telefonnummer.'; end if;
  if epost !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(epost) > 200 then raise exception 'Skriv inn ei gyldig e-postadresse.'; end if;
  if not coalesce(p_vilkar, false) then raise exception 'Du må godta leigevilkåra.'; end if;
  if p_start < now() - interval '1 hour' then raise exception 'Starttida har vore.'; end if;
  if p_slutt <= p_start then raise exception 'Sluttid må vere etter starttid.'; end if;
  if p_slutt - p_start > make_interval(days => i.maks_dagar) then raise exception 'Lengste leigeperiode er % dagar.', i.maks_dagar; end if;
  if p_start > now() + interval '1 year' then raise exception 'Du kan ikkje bestille så langt fram.'; end if;
  -- Enkel vern mot misbruk: maks 3 opne førespurnader per telefonnummer.
  if (select count(*) from public.utleige_reservasjon r join public.utleige_kunde k on k.id = r.kunde_id
      where k.telefon = tlf and r.status = 'ny') >= 3 then
    raise exception 'Du har alt fleire opne førespurnader. Ta kontakt med butikken.';
  end if;

  perform pg_advisory_xact_lock(hashtext(p_produkt::text));
  select e.id into eining from public.utleige_eining e
   where e.produkt_id = p_produkt and public.utleige_eining_ledig(e.id, p_start, p_slutt)
   order by e.kode limit 1;
  if eining is null then raise exception 'Utstyret er ikkje ledig i perioden. Prøv andre datoar.'; end if;

  insert into public.utleige_kunde (butikk_id, namn, telefon, epost)
  values (p.butikk_id, namn, tlf, epost)
  on conflict (butikk_id, telefon) do update set namn = excluded.namn, epost = excluded.epost
  returning id into kunde;

  pris := public.utleige_pris(p_produkt, p_start, p_slutt);
  insert into public.utleige_reservasjon (butikk_id, produkt_id, eining_id, kunde_id, start, slutt, status,
    pris_leige, gebyr, depositum, pris_total, kunde_melding, vilkar_godtatt_at)
  values (p.butikk_id, p_produkt, eining, kunde, p_start, p_slutt, 'ny',
    (pris->>'leige')::numeric, (pris->>'gebyr')::numeric, (pris->>'depositum')::numeric, (pris->>'total')::numeric,
    left(coalesce(p_melding, ''), 1000), now())
  returning * into res;

  return jsonb_build_object('nummer', res.nummer, 'start', res.start, 'slutt', res.slutt, 'total', res.pris_total, 'depositum', res.depositum);
exception
  when exclusion_violation then raise exception 'Utstyret vart nettopp booka av nokon andre. Prøv andre datoar.';
end $$;

